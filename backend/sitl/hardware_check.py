"""🩺 Do the log doctor's real-hardware checks catch real problems? Fly ArduCopter SITL with each problem built in.

  clean    : nothing wrong (every new check should pass)
  compass  : SIM_MAG_MOT = motor current leaking into the compass (mGauss per amp), like a compass next to the
             battery leads
  wobble   : roll/pitch rate gains (P and D) x 3.5, an over-tuned drone that rings

Each flight is the vibration harness's: take off, hover, dash 10 m out and back, land. Then the log goes through
the same analyze() the 🩺 Logs tab uses.

    .venv/bin/python -m backend.sitl.hardware_check [--write]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from backend.logdoctor.analyze import analyze

from .vibration import fly

RESULTS = Path(__file__).resolve().parents[2] / "docs" / "results"
DEFAULT_RATE_P, DEFAULT_RATE_D = 0.135, 0.0036  # ArduCopter 4.7 defaults for roll and pitch
CASES = {
    "clean": ("Nothing wrong", {}),
    "compass": ("Compass next to the power wires", {"SIM_MAG_MOT_X": 5.0, "SIM_MAG_MOT_Y": 3.0, "SIM_MAG_MOT_Z": -8.0}),
    "wobble": ("Rate gains x 3.5 (over-tuned)", {
        "ATC_RAT_RLL_P": DEFAULT_RATE_P * 3.5, "ATC_RAT_PIT_P": DEFAULT_RATE_P * 3.5,
        "ATC_RAT_RLL_D": DEFAULT_RATE_D * 3.5, "ATC_RAT_PIT_D": DEFAULT_RATE_D * 3.5}),
}
# ArduCopter's default LOG_BITMASK (180222) + bit 0 = ATTITUDE_FAST: attitude and rates at the loop rate (400 Hz)
# instead of 10 Hz. Tuning wobble is usually 5-20 Hz, invisible in a 10 Hz log.
FAST_ATTITUDE_LOG = {"LOG_BITMASK": 180223}
WATCH = ("compass_motor", "wobble", "motor_yaw", "battery_cells", "motors", "attitude")


def run(cases: list[str] | None = None, speedup: float = 1.0, say=print) -> dict:
    out = {}
    for key in cases or list(CASES):
        title, params = CASES[key]
        say(f"{title}: flying...")
        rec = fly({**FAST_ATTITUDE_LOG, **params}, speedup)
        rep = analyze(rec["log"])
        checks = {c["id"]: c for c in rep["checks"]}
        out[key] = {"title": title, "params": params,
                    "checks": {k: {"status": checks[k]["status"], "value": checks[k]["value"]} for k in WATCH if k in checks},
                    "fix_first": [f["id"] for f in rep["fix_first"]], "log": Path(rec["log"]).name}
        for k, c in out[key]["checks"].items():
            say(f"   {k:14s} {c['status']:5s} {c['value']}")
    return out


def write_results(res: dict) -> None:
    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "hardware-checks.json").write_text(json.dumps(res, indent=1))
    icon = {"ok": "✅", "warn": "⚠️", "bad": "❌", "info": "ℹ️"}
    lines = ["# Log doctor: real-hardware checks on ArduCopter 4.7.3 SITL", "",
             "Each flight has one problem built into the simulator; the log goes through the 🩺 Logs tab's analysis.",
             "Generated by `python -m backend.sitl.hardware_check --write`.", "",
             "| Flight | Compass vs motors | Wobble | Motors fighting on yaw | Battery per cell | Fix first |", "|---|---|---|---|---|---|"]
    for r in res.values():
        c = r["checks"]
        cell = lambda k: f"{icon[c[k]['status']]} {c[k]['value']}" if k in c else "–"  # noqa: E731
        lines.append(f"| {r['title']} | {cell('compass_motor')} | {cell('wobble')} | {cell('motor_yaw')} | "
                     f"{cell('battery_cells')} | {', '.join(r['fix_first']) or 'nothing'} |")
    (RESULTS / "hardware-checks.md").write_text("\n".join(lines) + "\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--case", action="append", choices=list(CASES))
    ap.add_argument("--speedup", type=float, default=1.0)
    ap.add_argument("--write", action="store_true", help="write docs/results/hardware-checks.md/.json")
    a = ap.parse_args(argv)
    res = run(a.case, a.speedup)
    if a.write:
        write_results(res)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
